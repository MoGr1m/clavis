/** Тип объекта: жилой или коммерческий */
export type ProjectType = "residential" | "commercial";

/** Роль участника команды проекта */
export type TeamMember = {
  /** Роль: Дизайнер, Декоратор, … */
  role: string;
  /** Имя как на проде / в DOCX */
  name: string;
};

/** Описание одного проекта */
export type Project = {
  /** URL-slug: /portfolio/[slug] */
  slug: string;
  /** Короткое имя на витрине */
  name: string;
  /** Подзаголовок / лид */
  lead: string;
  /** Жилой / коммерция */
  type: ProjectType;
  typeLabel: string;
  area: string;
  location: string;
  year: string;
  /** SEO-описание страницы кейса */
  seoDescription: string;
  /** Папка с webp-кадрами */
  imageDir: string;
  /** Имена файлов обложек (без пути) */
  images: string[];
  /** Длинное описание для страницы кейса */
  story: string[];
  /** Особенности / материалы */
  highlights: string[];
  /**
   * Команда проекта — сверка с clavis-interior.ru/portfolio/…
   * (DOCX как доп. источник; при расхождении приоритет у прода).
   */
  team: TeamMember[];
  /** Оптимизированный вертикальный ролик в /public/videos */
  video?: string;
  /** Постер к видео */
  videoPoster?: string;
};


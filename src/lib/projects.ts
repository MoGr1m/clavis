/** Найти проект по slug */
export function getProject(slug: string): Project | undefined {
  return PROJECTS.find((p) => p.slug === slug);
}

/** Путь к кадру проекта */
export function projectImage(project: Project, file: string): string {
  return `/projects/${project.imageDir}/${file}`;
}

/** Обложка проекта (первый кадр) */
export function projectCover(project: Project): string {
  return projectImage(project, project.images[0]);
}
